// Writes the license texts of every Rust crate linked into LegalSearch.exe
// (normal dependencies only, for the Windows target) to one text file.
// Their MIT / Apache-2.0 / ISC / Zlib terms require shipping these notices
// with binary distributions; the installer includes the result.
//
//   node scripts/gen-rust-licenses.mjs [output-file]
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = process.argv[2] ?? join(root, 'dist', 'licenses', 'THIRD_PARTY_RUST_CRATES.txt');

const meta = JSON.parse(
  execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--filter-platform', 'x86_64-pc-windows-msvc'], {
    cwd: join(root, 'native'),
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  }),
);
// The set of crates actually linked: `cargo tree` honours enabled features and
// the target; normal edges only (no build-dependencies, no dev-dependencies)
// and no proc-macros (they run at compile time and are not in the binary).
const tree = execFileSync(
  'cargo',
  ['tree', '--locked', '-e', 'normal,no-proc-macro', '--target', 'x86_64-pc-windows-msvc', '--prefix', 'none', '-f', '{p}'],
  { cwd: join(root, 'native'), encoding: 'utf8' },
);
const linked = new Set(
  tree
    .split(/\r?\n/)
    .map((l) => l.replace(/ \(\*\)$/, '').trim().split(' '))
    .filter((p) => p.length >= 2 && p[1].startsWith('v'))
    .map(([name, v]) => `${name}@${v.slice(1)}`),
);
const crates = meta.packages
  .filter((p) => linked.has(`${p.name}@${p.version}`) && !p.manifest_path.includes(`${join('legal-search', 'native')}Cargo.toml`))
  .filter((p) => p.name !== 'legalsearch');
crates.sort((a, b) => a.name.localeCompare(b.name));

let text =
  'Third-party Rust crates statically linked into LegalSearch.exe\n' +
  '==============================================================\n\n' +
  'Generated by scripts/gen-rust-licenses.mjs from Cargo.lock. Each entry lists the crate, its\n' +
  'declared license and the license/notice files shipped in the crate source.\n';
for (const p of crates) {
  const dir = dirname(p.manifest_path);
  const files = existsSync(dir)
    ? readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice|unlicense)/i.test(f)).sort()
    : [];
  text += `\n\n${'#'.repeat(78)}\n# ${p.name} ${p.version}\n# License: ${p.license ?? p.license_file ?? 'see files'}\n`;
  if (p.repository) text += `# Source: ${p.repository}\n`;
  text += `${'#'.repeat(78)}\n`;
  if (!files.length) text += '\n(no license file in the crate package; see the declared license above)\n';
  for (const f of files) text += `\n----- ${f} -----\n\n${readFileSync(join(dir, f), 'utf8').trim()}\n`;
}
text +=
  '\n\n' + '#'.repeat(78) + '\n# SQLite (bundled by libsqlite3-sys)\n' + '#'.repeat(78) +
  '\n\nThe SQLite source code is in the public domain: https://www.sqlite.org/copyright.html\n';

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, text);
console.log(`${crates.length} crates -> ${out}`);
