// Builds the extension into extension/build/ (load unpacked from there).
//
//   node build.mjs            development build (manifest "key" => stable dev ID)
//   node build.mjs --store    Chrome Web Store build (no "key"; the store assigns the ID)
//   node build.mjs --tests    bundles test/*.test.ts for `node --test`
//
// Everything identity-related comes from ../config/extension.config.json.
import { build } from 'esbuild';
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const config = JSON.parse(readFileSync(join(here, '..', 'config', 'extension.config.json'), 'utf8'));
const args = new Set(process.argv.slice(2));
const define = { __HOST_NAME__: JSON.stringify(config.hostName) };

if (args.has('--tests')) {
  const out = join(here, 'build-tests');
  rmSync(out, { recursive: true, force: true });
  const entries = readdirSync(join(here, 'test')).filter((f) => f.endsWith('.test.ts')).map((f) => join(here, 'test', f));
  await build({
    entryPoints: entries, outdir: out, bundle: true, platform: 'node', format: 'esm',
    target: 'node20', outExtension: { '.js': '.mjs' }, define, logLevel: 'warning',
    external: ['pdfjs-dist', 'pdfjs-dist/*'],
  });
  process.exit(0);
}

const out = join(here, 'build');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

await build({
  entryPoints: { sidepanel: join(here, 'src', 'sidepanel.ts'), background: join(here, 'src', 'background.ts') },
  outdir: out, bundle: true, format: 'esm', target: 'chrome116', platform: 'browser',
  define, legalComments: 'linked', sourcemap: false, minify: false, logLevel: 'warning',
});

const pdfjs = join(here, 'node_modules', 'pdfjs-dist');
cpSync(join(pdfjs, 'legacy', 'build', 'pdf.worker.min.mjs'), join(out, 'pdf.worker.min.mjs'));
cpSync(join(pdfjs, 'cmaps'), join(out, 'cmaps'), { recursive: true });
cpSync(join(pdfjs, 'LICENSE'), join(out, 'LICENSE-pdfjs.txt'));
cpSync(join(here, '..', 'LICENSE'), join(out, 'LICENSE.txt'));
cpSync(join(here, 'static'), out, { recursive: true });

const manifest = JSON.parse(readFileSync(join(here, 'manifest.template.json'), 'utf8'));
if (!args.has('--store')) {
  if (!config.manifestKey) throw new Error('config.manifestKey missing: run node scripts/gen-dev-key.mjs');
  manifest.key = config.manifestKey;
}
writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

// Installer defines generated from the same config (installer/LegalSearch.iss includes it).
const issDir = join(here, '..', 'installer', 'build');
mkdirSync(issDir, { recursive: true });
writeFileSync(
  join(issDir, 'config.iss'),
  `; GENERATED by extension/build.mjs from config/extension.config.json. Do not edit.\n` +
    `#define HostName "${config.hostName}"\n#define ExtensionId "${config.extensionId}"\n` +
    `#define ExtensionVersion "${manifest.version}"\n#define WebStoreUrl "${config.webStoreUrl ?? ''}"\n`,
);
console.log(`extension built (${args.has('--store') ? 'store' : 'dev'}; id ${args.has('--store') ? 'assigned by store' : config.extensionId})`);
